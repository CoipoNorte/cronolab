const GD_DIALOGUE = `class_name CronoDialogueRunner
extends Node

signal node_changed(node: Dictionary)
signal dialogue_ended
signal event_emitted(event_name: String)

var project: Dictionary = {}
var current: Dictionary = {}
var variables: Dictionary = {}

func load_file(path: String) -> bool:
    if not FileAccess.file_exists(path): return false
    var file := FileAccess.open(path, FileAccess.READ)
    var parsed = JSON.parse_string(file.get_as_text())
    if not parsed is Dictionary: return false
    project = parsed
    variables = project.get("variables", {}).duplicate(true)
    open_node(project.get("start", "inicio"))
    return true

func open_node(id: String) -> void:
    for node in project.get("nodes", []):
        if node.get("id", "") == id:
            current = node
            node_changed.emit(current)
            var event_name: String = current.get("event", "")
            if not event_name.is_empty(): event_emitted.emit(event_name)
            return
    push_warning("Nodo de dialogo inexistente: " + id)

func available_choices() -> Array:
    return current.get("choices", []).filter(func(choice): return _passes(choice.get("condition", {})))

func choose(index: int) -> void:
    var choices := available_choices()
    if index < 0 or index >= choices.size(): return
    var choice: Dictionary = choices[index]
    for effect in choice.get("effects", []): _apply(effect)
    var target: String = choice.get("target", "")
    if target.is_empty():
        current = {}
        dialogue_ended.emit()
    else: open_node(target)

func _passes(condition: Dictionary) -> bool:
    if condition.is_empty(): return true
    var left = variables.get(condition.get("key", ""), 0)
    var right = condition.get("value", 0)
    match condition.get("op", "=="):
        ">=": return left >= right
        "<=": return left <= right
        ">": return left > right
        "<": return left < right
        "!=": return left != right
        _: return left == right

func _apply(effect: Dictionary) -> void:
    var key: String = effect.get("key", "")
    match effect.get("op", "set"):
        "add": variables[key] = variables.get(key, 0) + effect.get("value", 0)
        "toggle": variables[key] = not variables.get(key, false)
        _: variables[key] = effect.get("value")
`;

